func TestGenerateAndValidateCheckedInPolicy(t *testing.T) {
	root := fixtureRoot(t)
	schema := readFile(t, filepath.Join(root, "schema/opentelemetry-1.41.0.yaml"))
	corpus := readFile(t, filepath.Join(root, "corpus/collector-schema-urls.json"))
	matrix, draft, err := Generate(schema, corpus)
	if err != nil {
		t.Fatalf("Generate() error = %v", err)
	}
	if err := Validate(schema, matrix, draft, false); err != nil {
		t.Fatalf("Validate(inventory) error = %v", err)
	}
	if err := Validate(schema, matrix, draft, true); err == nil || !strings.Contains(err.Error(), "manual_audit_required") {
		t.Fatalf("Validate(release-ready) error = %v", err)
	}
	if got := readFile(t, filepath.Join(root, "audit/compatibility-matrix.json")); !bytes.Equal(got, matrix) {
		t.Fatal("checked-in compatibility matrix differs from generated bytes")
	}
	if got := readFile(t, filepath.Join(root, "audit/required-source-urls-draft.json")); !bytes.Equal(got, draft) {
		t.Fatal("checked-in draft required URL policy differs from generated bytes")
	}
	release, err := PromoteRelease(draft)
	if err != nil {
		t.Fatal(err)
	}
	if err := Validate(schema, matrix, release, true); err != nil {
		t.Fatalf("Validate(release-ready) error = %v", err)
	}
	if got := readFile(t, filepath.Join(root, "audit/required-source-urls.yaml")); !bytes.Equal(got, release) {
		t.Fatal("checked-in release required URL policy differs from promoted bytes")
	}
}

func TestGenerateIsByteStable(t *testing.T) {
	root := fixtureRoot(t)
	schema := readFile(t, filepath.Join(root, "schema/opentelemetry-1.41.0.yaml"))
	corpus := readFile(t, filepath.Join(root, "corpus/collector-schema-urls.json"))
	matrix1, policy1, err := Generate(schema, corpus)
	if err != nil {
		t.Fatal(err)
	}
	matrix2, policy2, err := Generate(schema, corpus)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(matrix1, matrix2) || !bytes.Equal(policy1, policy2) {
		t.Fatal("Generate() is not byte-stable")
	}
}

func TestValidateRejectsInvalidPolicy(t *testing.T) {
	root := fixtureRoot(t)
	schema := readFile(t, filepath.Join(root, "schema/opentelemetry-1.41.0.yaml"))
	matrix := readFile(t, filepath.Join(root, "audit/compatibility-matrix.json"))
	policy := readFile(t, filepath.Join(root, "audit/required-source-urls-draft.json"))
	tests := []struct {
		name    string
		mutate  func([]byte) []byte
		release bool
		want    string
	}{
		{
			name: "canonical optional",
			mutate: func(data []byte) []byte {
				return bytes.Replace(data, []byte(`"requirement": "required"`), []byte(`"requirement": "optional"`), 1)
			},
			want: "canonical",
		},
		{
			name: "optional translated",
			mutate: func(data []byte) []byte {
				return bytes.Replace(data, []byte(`"disposition": "unknown"`), []byte(`"disposition": "translated"`), 1)
			},
			want: "optional disposition",
		},
		{
			name: "missing owner",
			mutate: func(data []byte) []byte {
				return bytes.Replace(data, []byte(`"classifier_owner": "otel-semconv-normalizer/semconv-maintainers"`), []byte(`"classifier_owner": ""`), 1)
			},
			want: "owner",
		},
		{
			name: "unknown field",
			mutate: func(data []byte) []byte {
				return bytes.Replace(data, []byte("{\n"), []byte("{\n  \"unexpected\": true,\n"), 1)
			},
			want: "unknown field",
		},
		{
			name:    "required incomplete release",
			mutate:  func(data []byte) []byte { return data },
			release: true,
			want:    "manual_audit_required",
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			err := Validate(schema, matrix, tt.mutate(append([]byte(nil), policy...)), tt.release)
			if err == nil || !strings.Contains(err.Error(), tt.want) {
				t.Fatalf("Validate() error = %v, want containing %q", err, tt.want)
			}
		})
	}
}

func fixtureRoot(t *testing.T) string {
	t.Helper()
	_, file, _, ok := runtime.Caller(0)
	if !ok {
		t.Fatal("cannot locate test source")
	}
	return filepath.Clean(filepath.Join(filepath.Dir(file), "..", "..", "testdata"))
}

func readFile(t *testing.T, path string) []byte {
	t.Helper()
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	return data
}
